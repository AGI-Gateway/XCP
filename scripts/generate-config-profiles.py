#!/usr/bin/env python3
"""
generate-config-profiles.py — emit deployment profiles and the config reference.

Both outputs are generated from `ops/config.py` (the settings registry) and
`ops/profiles.py` (the profiles), for the reason stated in those modules: a
hand-written example config goes stale silently. The file still parses, the
node still boots, and the setting the operator believed they set is simply
absent.

Outputs, both committed and both gated by --check in CI:

    deploy/profiles/<name>.env    copy-and-edit starting points
    docs/configuration.md         every setting, with the unsafe ones marked

    python scripts/generate-config-profiles.py [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from ops.config import SETTINGS, Role, secrets, unsafe          # noqa: E402
from ops.profiles import (PROFILES, NEVER_IN_A_PROFILE,         # noqa: E402
                          coverage, validate_all)

PROFILE_DIR = ROOT / "deploy" / "profiles"
DOC = ROOT / "docs" / "configuration.md"


def reference() -> str:
    cov = coverage()
    out = [
        "# Configuration",
        "",
        "<!-- Generated by scripts/generate-config-profiles.py. Do not edit. -->",
        "",
        f"{len(SETTINGS)} settings across {len(list(Role))} roles. "
        f"{len(unsafe())} weaken a control when moved off their default and "
        f"are marked **unsafe**. {len(secrets())} are secrets and belong in a "
        "secret backend, never in an image or a compose file.",
        "",
        "## Precedence",
        "",
        "Highest wins:",
        "",
        "1. An explicit argument passed to the SDK constructor",
        "2. An environment variable",
        "3. `xcp.toml` in the working directory",
        "4. The setting's documented default",
        "",
        "A setting the code cannot honour is not silently ignored. The gateway "
        "refuses to start when `XCP_PRIVATE_PEER_CIDRS` is set and the egress "
        "guard is unavailable, and when `XCP_SECURITY=1` and `xcpsec` is "
        "missing, because an operator who believes a control is active and is "
        "wrong is worse off than one who got an error.",
        "",
        "## Profiles",
        "",
        "| Profile | Purpose | Pinned | You supply |",
        "|---|---|---|---|",
    ]
    for p in PROFILES:
        purpose = p.purpose.split(".")[0] + "."
        out.append(f"| `{p.name}` | {purpose} | {len(p.settings)} | "
                   f"{len(p.operator_supplied)} |")
    out += ["", f"Files: `deploy/profiles/*.env`.", ""]

    if NEVER_IN_A_PROFILE:
        out += ["### Deliberately absent from every profile", ""]
        for name, why in sorted(NEVER_IN_A_PROFILE.items()):
            out.append(f"- **`{name}`** — {why}.")
        out += ["",
                "These are absent rather than pinned to a safe value, because "
                "a profile is a file operators copy and edit, and putting the "
                "name in front of them makes the unsafe edit a "
                "one-character change.", ""]

    assert not cov["unsafeUnmentioned"], cov["unsafeUnmentioned"]

    out += ["## Every setting", ""]
    for role in Role:
        rows = [s for s in SETTINGS if s.role is role]
        if not rows:
            continue
        out += [f"### {role.value}", "",
                "| Setting | Default | Notes |", "|---|---|---|"]
        for s in sorted(rows, key=lambda x: x.name):
            flags = []
            if s.unsafe:
                flags.append("**unsafe**")
            if s.secret:
                flags.append("**secret**")
            if s.required:
                flags.append("**required**")
            note = s.description.replace("|", "\\|")
            if flags:
                note = " ".join(flags) + " — " + note
            default = f"`{s.default}`" if s.default else "—"
            out.append(f"| `{s.name}` | {default} | {note} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--check", action="store_true",
                    help="fail if the committed output differs (for CI)")
    args = ap.parse_args()

    validate_all()

    written: dict[Path, tuple[str, str]] = {}
    PROFILE_DIR.mkdir(parents=True, exist_ok=True)
    for p in PROFILES:
        path = PROFILE_DIR / f"{p.name}.env"
        before = path.read_text() if path.exists() else ""
        text = p.to_env()
        path.write_text(text)
        written[path] = (before, text)

    before = DOC.read_text() if DOC.exists() else ""
    text = reference()
    DOC.write_text(text)
    written[DOC] = (before, text)

    changed = [p for p, (b, a) in written.items() if b != a]

    cov = coverage()
    for p in PROFILES:
        print(f"  {p.name + '.env':28} {len(p.settings):2} pinned, "
              f"{len(p.operator_supplied):2} operator-supplied")
    print(f"  {'docs/configuration.md':28} {cov['settings']} settings, "
          f"{len(unsafe())} unsafe, {len(secrets())} secret")
    print(f"\n  {cov['mentioned']}/{cov['settings']} settings appear in a "
          f"profile; {len(cov['unsafeUnmentioned'])} unsafe settings "
          f"unaccounted for")

    if args.check and changed:
        print("\nCommitted profiles are stale. Regenerate:", file=sys.stderr)
        print("    python scripts/generate-config-profiles.py", file=sys.stderr)
        for c in changed:
            print(f"  changed: {c.relative_to(ROOT)}", file=sys.stderr)
        return 1
    for c in changed:
        print(f"  updated {c.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
